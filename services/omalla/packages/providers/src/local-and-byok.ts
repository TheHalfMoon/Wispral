/**
 * Deepgram STT adapter (strictly optional BYOK via stored tenant credential).
 */
export class DeepgramStt implements SttProvider {
  readonly id = "deepgram";

  constructor(
    private readonly options: {
      apiKey: string;
      baseUrl?: string;
      model?: string;
      fetchImpl?: typeof fetch;
    },
  ) {}

  async transcribe(audio: Uint8Array, options: SttOptions = {}): Promise<TranscriptResult> {
    assertSafeIdentifier(options.language, "language");
    const fetchImpl = this.options.fetchImpl ?? fetch;
    const baseUrl = (this.options.baseUrl ?? "https://api.deepgram.com").replace(/\/+$/, "");
    const url = new URL(`${baseUrl}/v1/listen`);
    url.searchParams.set("model", this.options.model ?? "nova-2");
    url.searchParams.set("smart_format", "true");
    if (options.language && options.language !== "auto") {
      url.searchParams.set("language", options.language);
    }

    const response = await fetchImpl(url, {
      method: "POST",
      headers: {
        authorization: `Token ${this.options.apiKey}`,
        "content-type": options.mimeType ?? "audio/wav",
      },
      body: Buffer.from(audio),
      signal: options.signal,
    });
    if (!response.ok) {
      throw new OmallaError("provider_error", `Deepgram STT returned ${response.status}`, 502);
    }
    const payload = (await response.json()) as {
      results?: {
        channels?: Array<{
          alternatives?: Array<{ transcript?: string; confidence?: number }>;
          detected_language?: string;
        }>;
      };
    };
    const channel = payload.results?.channels?.[0];
    const alt = channel?.alternatives?.[0];
    const raw = (alt?.transcript ?? "").trim();
    const lang = channel?.detected_language ?? options.language;
    const text =
      isArabicLocale(lang) || containsArabic(raw)
        ? normalizeArabicText(raw, { foldTehMarbuta: false })
        : raw;
    return {
      text,
      confidence: alt?.confidence ?? 0.9,
      isFinal: true,
      ...(lang ? { language: lang } : {}),
    };
  }
}

/**
 * ElevenLabs TTS adapter (strictly optional BYOK via stored tenant credential).
 * Requests 16 kHz signed 16-bit PCM (`pcm_16000`) and wraps in standard RIFF WAV.
 */
export class ElevenLabsTts implements TtsProvider {
  readonly id = "elevenlabs";

  constructor(
    private readonly options: {
      apiKey: string;
      baseUrl?: string;
      modelId?: string;
      fetchImpl?: typeof fetch;
    },
  ) {}

  async synthesize(text: string, options: TtsOptions): Promise<SynthesizedAudio> {
    assertSafeIdentifier(options.voiceId, "voiceId");
    assertSafeIdentifier(options.language, "language");
    const fetchImpl = this.options.fetchImpl ?? fetch;
    const baseUrl = (this.options.baseUrl ?? "https://api.elevenlabs.io").replace(/\/+$/, "");
    const voiceId = encodeURIComponent(options.voiceId || "EXAVITQu4vr4xnSDxMaL");
    const response = await fetchImpl(
      `${baseUrl}/v1/text-to-speech/${voiceId}?output_format=pcm_16000`,
      {
        method: "POST",
        headers: {
          "xi-api-key": this.options.apiKey,
          "content-type": "application/json",
        },
        body: JSON.stringify({
          text,
          model_id: this.options.modelId ?? "eleven_multilingual_v2",
          ...(options.language ? { language_code: options.language.split("-")[0] } : {}),
        }),
        signal: options.signal,
      },
    );
    if (!response.ok) {
      throw new OmallaError("provider_error", `ElevenLabs TTS returned ${response.status}`, 502);
    }
    const rawBytes = new Uint8Array(await response.arrayBuffer());
    const contentType = response.headers.get("content-type") ?? "";
    const wav = contentType.includes("wav")
      ? rawBytes
      : encodeWav(rawBytes, { sampleRate: 16000, channels: 1, bitDepth: 16 });
    return { data: wav, mimeType: "audio/wav", durationMs: estimateSpeechDurationMs(text) };
  }
}

function appendRiffMetadataChunk(wav: Uint8Array, text: string): Uint8Array {
  const metaBytes = Buffer.from(text, "utf8");
  const pad = metaBytes.length % 2;
  const chunkTotal = 8 + metaBytes.length + pad;
  const out = new Uint8Array(wav.length + chunkTotal);
  out.set(wav, 0);

  const view = new DataView(out.buffer, out.byteOffset, out.byteLength);
  const riffSize = view.getUint32(4, true);
  view.setUint32(4, riffSize + chunkTotal, true);

  const offset = wav.length;
  out[offset] = 0x4f; // 'O'
  out[offset + 1] = 0x4d; // 'M'
  out[offset + 2] = 0x4c; // 'L'
  out[offset + 3] = 0x41; // 'A'
  view.setUint32(offset + 4, metaBytes.length, true);
  out.set(metaBytes, offset + 8);
  return out;
}

export function extractRiffMetadataChunk(wav: Uint8Array): string | null {
  if (wav.length < 12) return null;
  if (
    wav[0] !== 0x52 || // 'R'
    wav[1] !== 0x49 || // 'I'
    wav[2] !== 0x46 || // 'F'
    wav[3] !== 0x46 // 'F'
  ) {
    return null;
  }
  const view = new DataView(wav.buffer, wav.byteOffset, wav.byteLength);
  let offset = 12;
  while (offset + 8 <= wav.length) {
    const id = String.fromCharCode(
      wav[offset] ?? 0,
      wav[offset + 1] ?? 0,
      wav[offset + 2] ?? 0,
      wav[offset + 3] ?? 0,
    );
    const size = view.getUint32(offset + 4, true);
    const body = offset + 8;
    if (body + size > wav.length) break;
    if (id === "OMLA") {
      return Buffer.from(wav.subarray(body, body + size)).toString("utf8");
    }
    offset = body + size + (size % 2);
  }
  return null;
}

function hashString(input: string): number {
  let hash = 2166136261;
  for (let i = 0; i < input.length; i += 1) {
    hash ^= input.charCodeAt(i);
    hash = Math.imul(hash, 16777619);
  }
  return hash >>> 0;
}

function abortError(): Error {
  const error = new Error("aborted");
  error.name = "AbortError";
  return error;
}
