const execFileAsync = promisify(execFile);
const SAFE_CLI_IDENTIFIER = /^[A-Za-z0-9][A-Za-z0-9_.:-]{0,63}$/;

function assertSafeIdentifier(value: string | undefined, field: string): void {
  if (value === undefined || value === "") return;
  if (!SAFE_CLI_IDENTIFIER.test(value)) {
    throw new OmallaError(
      "validation",
      `invalid ${field}: must match /^[A-Za-z0-9][A-Za-z0-9_.:-]{0,63}$/ and never start with '-'`,
      400,
    );
  }
}

/**
 * Deterministic zero-paid-service local speech synthesizer.
 *
 * Generates genuine voiced PCM16 harmonics at 16 kHz (so VAD, RMS energy,
 * μ-law/A-law transcoding, RTP/SRTP framing, and studio waveform meters see
 * real non-silent audio) and appends a RIFF `OMLA` metadata chunk so local
 * `LoopbackStt` can deterministically verify round-trip utterances offline.
 */
export class LoopbackSynthTts implements TtsProvider {
  readonly id = "loopback";

  async synthesize(text: string, options: TtsOptions): Promise<SynthesizedAudio> {
    if (options.signal?.aborted) throw abortError();
    const durationMs = Math.max(240, estimateSpeechDurationMs(text));
    const sampleRate = 16000;
    const sampleCount = Math.max(160, Math.round((durationMs / 1000) * sampleRate));
    const pcm = new Uint8Array(sampleCount * 2);

    // Deterministic fundamental pitch seeded by voiceId + language
    const seed = hashString(`${options.voiceId}:${options.language ?? "en"}:${text}`);
    const f0 = 165 + (seed % 90);

    for (let i = 0; i < sampleCount; i += 1) {
      const t = i / sampleRate;
      const envelope = Math.min(1, i / 160, (sampleCount - i) / 160);
      const syllableMod = 0.65 + 0.35 * Math.sin(2 * Math.PI * 4.5 * t);
      const s1 = Math.sin(2 * Math.PI * f0 * t);
      const s2 = 0.45 * Math.sin(2 * Math.PI * f0 * 2 * t);
      const s3 = 0.2 * Math.sin(2 * Math.PI * f0 * 3 * t);
      const sample = Math.max(
        -32767,
        Math.min(32767, Math.round(envelope * syllableMod * (s1 + s2 + s3) * 9500)),
      );
      pcm[i * 2] = sample & 0xff;
      pcm[i * 2 + 1] = (sample >> 8) & 0xff;
    }

    const baseWav = encodeWav(pcm, { sampleRate, channels: 1, bitDepth: 16 });
    const wavWithMeta = appendRiffMetadataChunk(baseWav, text);
    return { data: wavWithMeta, mimeType: "audio/wav", durationMs };
  }
}

/**
 * Deterministic zero-paid-service local STT adapter.
 *
 * Extracts `OMLA` RIFF metadata when fed audio generated by `LoopbackSynthTts`,
 * or consumes queued scripted utterances, normalizing Arabic text when `ar*`
 * language is active.
 */
export class LoopbackStt implements SttProvider {
  readonly id = "loopback";
  private readonly queue: string[];

  constructor(initialQueue: string[] = []) {
    this.queue = [...initialQueue];
  }

  enqueue(text: string): void {
    this.queue.push(text);
  }

  async transcribe(audio: Uint8Array, options: SttOptions = {}): Promise<TranscriptResult> {
    if (options.signal?.aborted) throw abortError();
    const embedded = extractRiffMetadataChunk(audio);
    const raw = embedded ?? this.queue.shift() ?? "";
    const normalized =
      isArabicLocale(options.language) || containsArabic(raw)
        ? normalizeArabicText(raw, { foldTehMarbuta: false })
        : raw.trim();
    return {
      text: normalized,
      confidence: normalized ? 0.99 : 0,
      isFinal: true,
      ...(options.language ? { language: options.language } : {}),
    };
  }
}

/**
 * Local `whisper.cpp` adapter (HTTP server `/inference` or local CLI binary).
 * Never contacts any cloud service unless an operator explicitly sets `baseUrl`.
 */
export class WhisperCppStt implements SttProvider {
  readonly id = "whisper.cpp";

  constructor(
    private readonly options: {
      baseUrl?: string;
      model?: string;
      binaryPath?: string;
      modelPath?: string;
      fetchImpl?: typeof fetch;
    } = {},
  ) {}

  async transcribe(audio: Uint8Array, options: SttOptions = {}): Promise<TranscriptResult> {
    if (options.signal?.aborted) throw abortError();
    assertSafeIdentifier(options.language, "language");
    assertSafeIdentifier(this.options.model, "model");
    const bin = this.options.binaryPath ?? process.env.WHISPER_CPP_BIN;
    const modelPath = this.options.modelPath ?? process.env.WHISPER_CPP_MODEL;

    if (bin && modelPath && !this.options.baseUrl) {
      return this.transcribeCli(bin, modelPath, audio, options);
    }

    const fetchImpl = this.options.fetchImpl ?? fetch;
    const baseUrl = (
      this.options.baseUrl ??
      process.env.WHISPER_CPP_URL ??
      "http://127.0.0.1:8081"
    ).replace(/\/+$/, "");

    const form = new FormData();
    const arrayBuf = audio.buffer.slice(audio.byteOffset, audio.byteOffset + audio.byteLength) as ArrayBuffer;
    form.append("file", new Blob([arrayBuf], { type: options.mimeType ?? "audio/wav" }), "audio.wav");
    form.append("response_format", "json");
    if (options.language && options.language !== "auto") {
      form.append("language", options.language.split("-")[0] ?? options.language);
    }

    const response = await fetchImpl(`${baseUrl}/inference`, {
      method: "POST",
      body: form,
      signal: options.signal,
    });
    if (!response.ok) {
      throw new OmallaError("provider_error", `whisper.cpp server returned ${response.status}`, 502);
    }
    const payload = (await response.json()) as { text?: string; language?: string };
    const rawText = (payload.text ?? "").trim();
    const lang = payload.language ?? options.language;
    const text =
      isArabicLocale(lang) || containsArabic(rawText)
        ? normalizeArabicText(rawText, { foldTehMarbuta: false })
        : rawText;
    return {
      text,
      confidence: 0.92,
      isFinal: true,
      ...(lang ? { language: lang } : {}),
    };
  }

  private async transcribeCli(
    bin: string,
    modelPath: string,
    audio: Uint8Array,
    options: SttOptions,
  ): Promise<TranscriptResult> {
    const dir = await mkdtemp(path.join(tmpdir(), "omalla-whisper-"));
    const wavPath = path.join(dir, "in.wav");
    try {
      await writeFile(wavPath, audio);
      const args = ["-m", modelPath, "-f", wavPath, "-nt"];
      if (options.language && options.language !== "auto") {
        args.push("-l", options.language.split("-")[0] ?? "en");
      }
      const { stdout } = await execFileAsync(bin, args, {
        timeout: 30_000,
        windowsHide: true,
      });
      const rawText = String(stdout).trim();
      const text =
        isArabicLocale(options.language) || containsArabic(rawText)
          ? normalizeArabicText(rawText, { foldTehMarbuta: false })
          : rawText;
      return { text, confidence: 0.9, isFinal: true, ...(options.language ? { language: options.language } : {}) };
    } finally {
      await rm(dir, { recursive: true, force: true }).catch(() => {});
    }
  }
}

/**
 * Local `piper` neural TTS adapter (local HTTP server or CLI binary).
 */
export class PiperTts implements TtsProvider {
  readonly id = "piper";

  constructor(
    private readonly options: {
      baseUrl?: string;
      binaryPath?: string;
      modelPath?: string;
      fetchImpl?: typeof fetch;
    } = {},
  ) {}

  async synthesize(text: string, options: TtsOptions): Promise<SynthesizedAudio> {
    if (options.signal?.aborted) throw abortError();
    assertSafeIdentifier(options.voiceId, "voiceId");
    assertSafeIdentifier(options.language, "language");
    const bin = this.options.binaryPath ?? process.env.PIPER_BIN;
    const modelPath = this.options.modelPath ?? process.env.PIPER_MODEL;

    if (bin && modelPath && !this.options.baseUrl) {
      return this.synthesizeCli(bin, modelPath, text);
    }

    const fetchImpl = this.options.fetchImpl ?? fetch;
    const baseUrl = (
      this.options.baseUrl ??
      process.env.PIPER_URL ??
      "http://127.0.0.1:5000"
    ).replace(/\/+$/, "");

    const response = await fetchImpl(`${baseUrl}/`, {
      method: "POST",
      headers: { "content-type": "application/json" },
      body: JSON.stringify({
        text,
        voice: options.voiceId,
        length_scale: options.speed && options.speed > 0 ? Number((1 / options.speed).toFixed(2)) : 1,
      }),
      signal: options.signal,
    });
    if (!response.ok) {
      throw new OmallaError("provider_error", `Piper TTS server returned ${response.status}`, 502);
    }
    const data = new Uint8Array(await response.arrayBuffer());
    return { data, mimeType: "audio/wav", durationMs: estimateSpeechDurationMs(text) };
  }

  private async synthesizeCli(bin: string, modelPath: string, text: string): Promise<SynthesizedAudio> {
    const dir = await mkdtemp(path.join(tmpdir(), "omalla-piper-"));
    const outPath = path.join(dir, "out.wav");
    try {
      await new Promise<void>((resolve, reject) => {
        const child = execFile(
          bin,
          ["--model", modelPath, "--output_file", outPath],
          { timeout: 20_000, windowsHide: true },
          (error) => {
            if (error) reject(error);
            else resolve();
          },
        );
        child.stdin?.end(`${text}\n`, "utf8");
      });
      const data = new Uint8Array(await readFile(outPath));
      return { data, mimeType: "audio/wav", durationMs: estimateSpeechDurationMs(text) };
    } finally {
      await rm(dir, { recursive: true, force: true }).catch(() => {});
    }
  }
}

